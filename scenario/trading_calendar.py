"""NYSE trading-day arithmetic from the committed holiday file (no network).

`scenario/nyse_holidays.json` is generated by scripts/gen_nyse_holidays.py from
gaps in SPY's daily history plus the NYSE-published future holidays.
"""

from __future__ import annotations

import json
from datetime import date, timedelta
from functools import lru_cache
from pathlib import Path

HOLIDAYS_PATH = Path(__file__).with_name("nyse_holidays.json")


@lru_cache(maxsize=1)
def _data() -> dict:
    return json.loads(HOLIDAYS_PATH.read_text())


@lru_cache(maxsize=1)
def closed_days() -> frozenset[date]:
    return frozenset(date.fromisoformat(d) for d in _data()["closed"])


def coverage() -> tuple[date, date]:
    data = _data()
    return date.fromisoformat(data["first_day"]), date.fromisoformat(data["last_day"])


def _check_range(day: date) -> None:
    first, last = coverage()
    if not first <= day <= last:
        raise ValueError(f"{day} is outside the holiday calendar ({first} to {last})")


def is_trading_day(day: date) -> bool:
    _check_range(day)
    return day.weekday() < 5 and day not in closed_days()


def next_trading_day(day: date) -> date:
    """The first trading day on or after `day`."""
    while not is_trading_day(day):
        day += timedelta(days=1)
    return day


def add_trading_days(day: date, n: int) -> date:
    """Move n trading days from a trading day (n may be negative)."""
    if not is_trading_day(day):
        raise ValueError(f"{day} is not a trading day")
    step = 1 if n >= 0 else -1
    remaining = abs(n)
    while remaining:
        day += timedelta(days=step)
        if is_trading_day(day):
            remaining -= 1
    return day
